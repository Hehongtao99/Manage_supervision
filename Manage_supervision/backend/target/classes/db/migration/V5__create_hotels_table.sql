-- 创建酒店表
CREATE TABLE IF NOT EXISTS hotels (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    name VARCHAR(100) NOT NULL COMMENT '酒店名称',
    description TEXT COMMENT '酒店描述',
    province_id BIGINT NOT NULL COMMENT '省份ID',
    city_id BIGINT COMMENT '城市ID',
    district_id BIGINT COMMENT '区县ID',
    address VARCHAR(255) COMMENT '详细地址',
    level VARCHAR(20) COMMENT '酒店等级',
    image_url VARCHAR(255) COMMENT '酒店图片',
    contact_phone VARCHAR(20) COMMENT '联系电话',
    scenic_spot_id BIGINT COMMENT '关联景区ID',
    distance_to_spot DECIMAL(10,2) COMMENT '距离景区距离(公里)',
    start_price DECIMAL(10,2) COMMENT '起始价格',
    status VARCHAR(20) NOT NULL DEFAULT 'active' COMMENT '状态：active-启用，inactive-禁用',
    sort INT DEFAULT 0 COMMENT '排序值',
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    INDEX idx_province_id (province_id),
    INDEX idx_city_id (city_id),
    INDEX idx_district_id (district_id),
    INDEX idx_scenic_spot_id (scenic_spot_id),
    INDEX idx_status (status),
    INDEX idx_sort (sort),
    FOREIGN KEY (province_id) REFERENCES regions(id),
    FOREIGN KEY (city_id) REFERENCES regions(id),
    FOREIGN KEY (district_id) REFERENCES regions(id),
    FOREIGN KEY (scenic_spot_id) REFERENCES scenic_spots(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='酒店表'; 